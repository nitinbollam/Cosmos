/**
 * Generate per-service Deployment/Service/HPA YAML (pattern matches infra/k8s/base/auth-service.yaml).
 * Usage: node scripts/gen-k8s-services.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, '..')
const DIR = path.join(ROOT, 'infra', 'k8s', 'base')

/** [resourceNameSuffix, containerPort] — excludes auth-service (already authored). */
const SERVICES = [
  ['gateway-service', 3000],
  ['tenant-service', 3002],
  ['inventory-service', 3003],
  ['wms-service', 3004],
  ['order-service', 3005],
  ['purchasing-service', 3006],
  ['compliance-service', 3007],
  ['storefront-service', 3008],
  ['pos-service', 3009],
  ['crm-service', 3010],
  ['dispatch-service', 3011],
  ['payment-service', 3012],
  ['ledger-service', 3013],
  ['analytics-service', 3014],
  ['notification-service', 3015],
]

function doc(name, port) {
  const lbl = name
  const image = `REPLACE_REGISTRY/cosmos-${name}:latest`
  return `apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${lbl}
  namespace: cosmos
  labels: { app: ${lbl} }
spec:
  replicas: 2
  selector:
    matchLabels: { app: ${lbl} }
  template:
    metadata:
      labels: { app: ${lbl} }
    spec:
      containers:
        - name: ${lbl}
          image: ${image}
          ports:
            - containerPort: ${port}
          envFrom:
            - configMapRef: { name: cosmos-config }
            - secretRef: { name: cosmos-secrets }
          env:
            - name: PORT
              value: "${port}"
            - name: SERVICE_NAME
              value: "${lbl}"
            - name: COSMOS_OTEL_ENABLED
              value: "false"
          readinessProbe:
            httpGet: { path: /api/v1/health, port: ${port} }
            initialDelaySeconds: 5
            periodSeconds: 10
          livenessProbe:
            httpGet: { path: /api/v1/health, port: ${port} }
            initialDelaySeconds: 15
            periodSeconds: 20
          resources:
            requests: { cpu: 100m, memory: 256Mi }
            limits:   { cpu: 500m, memory: 512Mi }
---
apiVersion: v1
kind: Service
metadata:
  name: ${lbl}
  namespace: cosmos
spec:
  selector: { app: ${lbl} }
  ports:
    - port: ${port}
      targetPort: ${port}
      name: http
---
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: ${lbl}
  namespace: cosmos
spec:
  scaleTargetRef:
    apiVersion: apps/v1
    kind: Deployment
    name: ${lbl}
  minReplicas: 2
  maxReplicas: 8
  metrics:
    - type: Resource
      resource:
        name: cpu
        target: { type: Utilization, averageUtilization: 70 }
`
}

fs.mkdirSync(DIR, { recursive: true })
const resourcesList = [`namespace.yaml`, `configmap.yaml`, `secret.yaml`, `auth-service.yaml`]

for (const [name, port] of SERVICES) {
  const file = `${name}.yaml`
  fs.writeFileSync(path.join(DIR, file), doc(name, port), 'utf8')
  resourcesList.push(file)
}

const kust = `# Generated list includes autogenerated workloads + auth baseline.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: cosmos
resources:
${resourcesList.map((r) => `  - ${r}`).join('\n')}
`
fs.writeFileSync(path.join(DIR, 'kustomization.yaml'), kust, 'utf8')
console.log(`Wrote ${SERVICES.length} service bundles + kustomization.yaml`)
